/**
 * Enclosure handoff (OpenSCAD)
 *
 * The mechanical side -- cases, mounts, brackets -- belongs to the existing
 * `openscad` / `three-d` CutuCircuits extensions, so rather than reinventing 3D CAD
 * we hand them a parametric enclosure generated from the board: a two-part box
 * sized to the board outline, PCB standoffs at the corners, and side cutouts at
 * each connector's position. The output is plain OpenSCAD (`.scad`) the OpenSCAD
 * extension opens directly; its STL/STEP export then feeds three-d.
 */

import type { AnyCircuitElement } from '../circuit/circuitJson';
import { getBoardOutline, getConnectors } from './board';

export interface EnclosureOptions {
  wall?: number;
  standoffHeight?: number;
  clearance?: number;
  lid?: boolean;
}

export function generateEnclosureScad(
  elements: AnyCircuitElement[],
  name: string,
  opts: EnclosureOptions = {},
): { scad: string; warnings: string[] } {
  const outline = getBoardOutline(elements);
  const connectors = getConnectors(elements);
  const warnings: string[] = [];
  if (!outline.explicit) warnings.push('Board size inferred from parts; set a sized <board> for an exact fit.');
  if (connectors.length === 0) warnings.push('No connectors detected; no side cutouts were generated.');

  const wall = opts.wall ?? 2;
  const standoff = opts.standoffHeight ?? 4;
  const clr = opts.clearance ?? 0.5;
  const lid = opts.lid ?? true;

  const bw = round2(outline.width);
  const bh = round2(outline.height);
  const innerW = round2(bw + clr * 2);
  const innerH = round2(bh + clr * 2);
  const innerDepth = round2(standoff + 8); // room for parts above the board

  // Connector cutouts: position relative to the board centre -> inner box.
  const cutouts = connectors
    .map((c) => {
      const relX = round2(c.x - outline.center.x);
      const relY = round2(c.y - outline.center.y);
      const h = round2(Math.max(c.height, c.width, 3) + clr * 2);
      // Place the cutout on the nearest wall (X edges here for simplicity).
      const onRight = relX >= 0;
      return `    // ${c.name} (${c.ftype ?? 'connector'})
    translate([${onRight ? 'innerW/2' : '-innerW/2 - wall'}, ${relY} - ${h}/2, standoff])
      cube([wall + 1, ${h}, ${h}]);`;
    })
    .join('\n');

  const scad = `// ${name} enclosure -- generated by CutuCircuits Electronics Studio
// Hand off to the OpenSCAD extension; export STL/STEP for the three-d extension.
// Board: ${bw} x ${bh} mm${outline.explicit ? '' : ' (inferred)'}

board_w = ${bw};
board_h = ${bh};
wall = ${wall};
clearance = ${clr};
standoff = ${standoff};
innerW = ${innerW};
innerH = ${innerH};
innerDepth = ${innerDepth};
$fn = 32;

module pcb_standoff(d_outer = 5, d_hole = 2.6, h = standoff) {
  difference() {
    cylinder(d = d_outer, h = h);
    translate([0, 0, -0.1]) cylinder(d = d_hole, h = h + 0.2);
  }
}

module enclosure_base() {
  difference() {
    // Outer shell
    translate([-(innerW/2 + wall), -(innerH/2 + wall), 0])
      cube([innerW + wall*2, innerH + wall*2, innerDepth + wall]);
    // Inner cavity
    translate([-innerW/2, -innerH/2, wall])
      cube([innerW, innerH, innerDepth + 1]);
    // Connector cutouts
${cutouts || '    // (no connector cutouts)'}
  }
  // Corner standoffs for the PCB
  for (sx = [-1, 1], sy = [-1, 1])
    translate([sx * (board_w/2 - 3), sy * (board_h/2 - 3), wall])
      pcb_standoff();
}

module enclosure_lid() {
  translate([0, ${round2(innerH + wall * 2 + 5)}, 0]) {
    translate([-(innerW/2 + wall), -(innerH/2 + wall), 0])
      cube([innerW + wall*2, innerH + wall*2, wall]);
    // Lip that drops into the base
    translate([-innerW/2, -innerH/2, wall])
      difference() {
        cube([innerW, innerH, wall]);
        translate([2, 2, -0.1]) cube([innerW - 4, innerH - 4, wall + 0.2]);
      }
  }
}

enclosure_base();
${lid ? 'enclosure_lid();' : '// lid disabled'}
`;

  return { scad, warnings };
}

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}
