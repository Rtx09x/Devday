/**
 * Manufacturing export
 *
 * The universal fab package: Gerber X2 + Excellon drill + BOM + pick-and-place,
 * generated from Circuit JSON. We return a filename -> content map; the caller
 * writes it to disk (or zips it). Vendor-agnostic by design -- no credentials,
 * no ordering API. Direct fab-API ordering is a deliberate future option.
 *
 * Exporters are imported lazily so the (large) gerber/drill code only loads when
 * the user actually exports.
 */

import type { AnyCircuitElement } from './circuitJson';
import { hasPcbElements } from './circuitJson';

export interface FabBundle {
  files: Record<string, string>;
  warnings: string[];
}

export async function buildFabBundle(
  circuitJson: AnyCircuitElement[],
  baseName: string,
): Promise<FabBundle> {
  const warnings: string[] = [];
  const files: Record<string, string> = {};

  if (!hasPcbElements(circuitJson)) {
    warnings.push('No PCB elements found -- Gerber/drill output will be empty. Did you place parts on the board?');
  }

  // Our `AnyCircuitElement` is intentionally loose; the exporters want the
  // strict circuit-json union. They are runtime-compatible -- cast at the seam.
  const cj = circuitJson as never;

  // Gerber layers.
  try {
    const gerber = await import('circuit-json-to-gerber');
    const layers = gerber.convertSoupToGerberCommands(cj);
    const stringified = gerber.stringifyGerberCommandLayers(layers);
    for (const [layerName, content] of Object.entries(stringified)) {
      files[`gerber/${baseName}-${layerName}.gbr`] = content as string;
    }
    // Excellon drill file.
    const drillCommands = gerber.convertSoupToExcellonDrillCommands({
      circuitJson: cj,
      is_plated: true,
    });
    files[`gerber/${baseName}.drl`] = gerber.stringifyExcellonDrill(drillCommands);
  } catch (err) {
    warnings.push(`Gerber/drill export failed: ${err instanceof Error ? err.message : String(err)}`);
  }

  // Bill of materials.
  try {
    const bomMod = await import('circuit-json-to-bom-csv');
    const rows = await bomMod.convertCircuitJsonToBomRows({ circuitJson: cj });
    files[`${baseName}-bom.csv`] = bomMod.convertBomRowsToCsv(rows);
  } catch (err) {
    warnings.push(`BOM export failed: ${err instanceof Error ? err.message : String(err)}`);
  }

  // Pick and place.
  try {
    const pnp = await import('circuit-json-to-pnp-csv');
    files[`${baseName}-pick-and-place.csv`] = pnp.convertCircuitJsonToPickAndPlaceCsv(cj);
  } catch (err) {
    warnings.push(`Pick-and-place export failed: ${err instanceof Error ? err.message : String(err)}`);
  }

  // README so the bundle is self-describing when handed to any fab.
  files[`${baseName}-README.txt`] = [
    `Fab package for "${baseName}" -- generated by CutuCircuits Electronics Studio.`,
    '',
    'Contents:',
    '  gerber/*.gbr   Gerber X2 copper/mask/silk/edge layers',
    '  gerber/*.drl   Excellon drill file',
    `  ${baseName}-bom.csv               Bill of materials`,
    `  ${baseName}-pick-and-place.csv    Component placement (CPL)`,
    '',
    'Zip the contents of this folder and upload to your fab (JLCPCB, PCBWay, OSH Park, ...).',
  ].join('\n');

  return { files, warnings };
}
