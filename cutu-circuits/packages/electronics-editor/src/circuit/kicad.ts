/** KiCad bridge for users who need a mature manual-EDA handoff. */

import type { AnyCircuitElement } from './circuitJson.ts';

export interface KicadProjectBundle {
  files: Record<string, string>;
  warnings: string[];
}

export async function buildKicadProject(
  circuitJson: AnyCircuitElement[],
  projectName: string,
): Promise<KicadProjectBundle> {
  const files: Record<string, string> = {};
  const warnings: string[] = [];
  const safeName = projectName.replace(/[^A-Za-z0-9_.-]+/g, '-').replace(/^-+|-+$/g, '') || 'circuit';
  const input = circuitJson as never;
  const {
    CircuitJsonToKicadSchConverter,
    CircuitJsonToKicadPcbConverter,
    CircuitJsonToKicadProConverter,
  } = await import('circuit-json-to-kicad');

  try {
    const schematic = new CircuitJsonToKicadSchConverter(input);
    schematic.runUntilFinished();
    files[`${safeName}.kicad_sch`] = normalizeSExpressionIds(schematic.getOutputString(), `${safeName}:schematic`);
  } catch (error) {
    warnings.push(`Schematic conversion failed: ${message(error)}`);
  }

  try {
    const pcb = new CircuitJsonToKicadPcbConverter(input, { projectName: safeName });
    pcb.runUntilFinished();
    files[`${safeName}.kicad_pcb`] = normalizeSExpressionIds(pcb.getOutputString(), `${safeName}:pcb`);
  } catch (error) {
    warnings.push(`PCB conversion failed: ${message(error)}`);
  }

  try {
    const project = new CircuitJsonToKicadProConverter(input, {
      projectName: safeName,
      schematicFilename: `${safeName}.kicad_sch`,
      pcbFilename: `${safeName}.kicad_pcb`,
    });
    project.runUntilFinished();
    files[`${safeName}.kicad_pro`] = normalizeProjectJson(project.getOutputString(), safeName);
  } catch (error) {
    warnings.push(`Project conversion failed: ${message(error)}`);
  }

  files[`${safeName}-HANDOFF.txt`] = [
    `KiCad handoff for "${safeName}" — generated by CutuCircuits Electronics Studio.`,
    '',
    'Open the .kicad_pro file in KiCad 9 or newer.',
    'Before fabrication, run KiCad ERC/DRC, inspect footprints, verify net classes,',
    'and review the board against your manufacturer\'s current design rules.',
    warnings.length ? `\nConversion notes:\n- ${warnings.join('\n- ')}` : '',
  ].filter(Boolean).join('\n');

  return { files, warnings };
}

function message(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function normalizeSExpressionIds(content: string, namespace: string): string {
  const ids = new Map<string, string>();
  return content.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi, (id) => {
    const normalized = id.toLowerCase();
    let replacement = ids.get(normalized);
    if (!replacement) {
      replacement = deterministicUuid(`${namespace}:${ids.size}`);
      ids.set(normalized, replacement);
    }
    return replacement;
  });
}

function normalizeProjectJson(content: string, projectName: string): string {
  const project = JSON.parse(content) as {
    head?: Record<string, unknown>;
    sheets?: Array<[string, string]>;
  };
  if (project.head) {
    project.head.created = '1970-01-01T00:00:00.000Z';
    project.head.modified = '1970-01-01T00:00:00.000Z';
  }
  if (Array.isArray(project.sheets)) {
    project.sheets = project.sheets.map((entry, index) => [
      deterministicToken(`${projectName}:sheet:${index}`),
      entry[1],
    ]);
  }
  return `${JSON.stringify(project, null, 2)}\n`;
}

function deterministicUuid(value: string): string {
  const hex = [0, 1, 2, 3].map((seed) => fnv1a(value, seed).toString(16).padStart(8, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function deterministicToken(value: string): string {
  return `${fnv1a(value, 0).toString(36)}${fnv1a(value, 1).toString(36)}`.slice(0, 11);
}

function fnv1a(value: string, seed: number): number {
  let hash = (0x811c9dc5 ^ seed) >>> 0;
  for (let index = 0; index < value.length; index++) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash;
}
