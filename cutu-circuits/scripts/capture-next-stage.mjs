function pixelDifference(beforeBuffer, afterBuffer) {
  const before = PNG.sync.read(beforeBuffer), after = PNG.sync.read(afterBuffer);
  expect([after.width, after.height]).toEqual([before.width, before.height]);
  let changedPixels = 0;
  for (let i = 0; i < before.data.length; i += 4) if ([0, 1, 2].some(channel => Math.abs(before.data[i + channel] - after.data[i + channel]) > 8)) changedPixels++;
  return { changedPixels, width: before.width, height: before.height };
}
