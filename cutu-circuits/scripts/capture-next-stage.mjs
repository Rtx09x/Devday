async function json(url, data, method = data === undefined ? "GET" : "POST") {
  const response = await fetch(`${api}${url}`, { method, headers: data === undefined ? {} : { "Content-Type": "application/json" }, body: data === undefined ? undefined : JSON.stringify(data) });
  const result = await response.json();
  if (!response.ok) throw new Error(`${method} ${url}: ${response.status} ${JSON.stringify(result)}`);
  return result;
}
